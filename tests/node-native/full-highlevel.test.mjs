test('full Fake snapshot seeding, rich records, observers, message constructors and clearing', async t => {
  const { runtime, adapter, bus } = await fixture(t)
  const snapshot = adapter.fake.createSnapshot(model)
  Object.assign(snapshot, { fwVersion: 0x26010100, productId: 0xf1234567, hwVersion: 0x25010100, calFlag: 1, rawAngleDeg: 12, calAngleDeg: 13 })
  adapter.fake.seedMotor(0, 2, snapshot)
  adapter.fake.disableAutoCreateMotor()
  adapter.fake.enablePositionError(false)
  const motor = await bus.getMotor(2, { model })
  assert.equal((await motor.getParameter(api.MotorParameter.ProductId)), 0xf1234567)
  assert.equal(adapter.fake.getMotorSnapshot(0, 2).ranges.fwVersion, snapshot.ranges.fwVersion)
  assert.equal(adapter.fake.getMotorSnapshot(0, 2).productId, snapshot.productId)
  const records = []
  adapter.fake.setDecodedCommandObserver(record => records.push(record))
  adapter.fake.enableCommandRecording(false)
  const before = adapter.fake.getDecodedCommandRecords().length
  await motor.posControl({ position: 0.2, speed: 1, current: 1, feedbackType: 0, feedback: 2 })
  await delay(20)
  assert.equal(adapter.fake.getDecodedCommandRecords().length, before)
  assert.ok(records.some(record => record.kind === api.FakeCommandKind.PosControl && record.payload.feedbackType === 2))
  assert.equal(typeof records.at(-1).formattedText, 'string')
  adapter.fake.clearDecodedCommandObserver()
  adapter.fake.enableCommandRecording()
  await motor.curControl({ current: 0, feedbackType: 0 })
  assert.equal(adapter.fake.getLastDecodedCommand().kind, api.FakeCommandKind.CurControl)
  assert.ok(Array.isArray(adapter.fake.getReplyRecords()))
  assert.ok(Array.isArray(adapter.fake.getFormattedSentCommands()))
  assert.ok(Array.isArray(adapter.fake.getRawSentMessages()))
  const status = { error: 0, position: 1, speed: 2, current: 3, motorTemperature: 25, mosTemperature: 30 }
  const feedback = adapter.fake.makeFeedbackMessage(0, 2, status)
  adapter.fake.injectMessage(feedback)
  assert.ok(motor.getStatus(0).hasValue)
  assert.ok(adapter.fake.makeParameterReply(0, 2, api.MotorParameter.Position, [0, 0, 0, 0]).data.len > 0)
  assert.ok(adapter.fake.makeWriteAck(0, 2, api.MotorParameter.CanTimeout, [0, 0]).data.len > 0)
  assert.equal(runtime.manager.dispatchReceive(adapter, 0, feedback.data), true)
  assert.equal(runtime.manager.dispatchUnknownReceive(adapter, 0, { id: 99, frameFlags: 0, len: 1, data: [0] }), true)
  adapter.fake.clearCommandRecords()
  assert.equal(adapter.fake.getDecodedCommandRecords().length, 0)
})

test('child disposal invalidates native aliases and fresh wrappers can be created', async t => {
  const runtime = await api.createEncosRuntime()
  t.after(() => runtime.dispose())
  const first = runtime.createFakeAdapter({ interfaceName: 'full-wrapper-aliases' })
  const second = runtime.createFakeAdapter({ interfaceName: 'full-wrapper-aliases' })
  first.fake.seedMotor(0, 1, model)
  const busA = first.getBus(0)
  const busB = second.getBus(0)
  const motorA = await busA.getMotor(1, model)
  const motorB = await busB.getMotor(1, model)
  motorA.dispose()
  assert.throws(() => motorB.getStatus(), /invalid|disposed|handle/i)
  const fresh = await busB.getMotor(1, model)
  assert.notEqual(fresh, motorB)
  assert.ok(fresh.getProperties())
  const battery = busB.getBattery(0)
  battery.dispose()
  assert.notEqual(busB.getBattery(0), battery)
  const imu = busB.getImu(0)
  imu.dispose()
  const pms = busB.getPms()
  pms.dispose()
  assert.equal(runtime.deleteBus(busA), true)
  assert.throws(() => fresh.getStatus(), /invalid|disposed|handle/i)
  assert.notEqual(second.getBus(0), busB)
  assert.equal(runtime.deleteAdapterByInterfaceName(first.interfaceName), true)
  assert.equal(first.disposed, true)
  assert.equal(second.disposed, true)
})

test('application logger and CSV writer wrappers expose lifecycle and helper conversion', async t => {
  const { runtime } = await fixture(t)
  assert.equal(api.logLevelFromInt(99), api.LogLevel.Info)
  assert.equal(api.logLevelFromString('WARNING'), api.LogLevel.Warn)
  assert.equal(api.logLevelToString(api.LogLevel.Error), 'error')
  assert.equal(api.logLevelToInt(api.LogLevel.Trace), 0)
  const logger = runtime.createLogger('full-api-log', api.LogLevel.Off)
  assert.equal(logger.name(), 'full-api-log')
  logger.setLevel(api.LogLevel.Off)
  assert.equal(logger.level(), api.LogLevel.Off)
  for (const method of ['trace', 'debug', 'info', 'warn', 'error', 'critical']) logger[method]('value {}', 1)
  logger.flush()
  logger.dispose()
  assert.throws(() => logger.info('closed'), /disposed/)
  const directory = mkdtempSync(join(tmpdir(), 'encos-native-ts-'))
  t.after(() => rmSync(directory, { recursive: true, force: true }))
  const baseName = join(directory, 'data')
  const writer = runtime.createLogWriter(baseName, ['n', 's'])
  writer.write(NaN, 'a,b')
  writer.write(1n, undefined)
  assert.throws(() => writer.write(1), /column|field|count|row/i)
  writer.flush()
  assert.equal(writer.getBaseName(), baseName)
  assert.ok(existsSync(writer.getFileName()))
  writer.dispose()
  assert.throws(() => writer.write(1, 2), /disposed/)
  runtime.clearLoggers()
})


