test('soft sync retains motion controls while queries, Stop, Brake, IMU and PMS submit immediately', async t => {
  const { adapter, bus } = await fixture(t)
  const motor = await bus.getMotor(1, model)
  const pms = bus.getPms()
  adapter.fake.clearCommandRecords()
  bus.setSyncMode(true)
  await motor.pvtControl({ kp: 1, kd: 1, position: 0, speed: 0, torque: 0, feedbackType: 0 })
  await motor.posControl({ position: 0, speed: 1, current: 1, feedbackType: 0 })
  await motor.spdControl({ speed: 1, current: 1, feedbackType: 0 })
  await motor.curControl({ current: 1, feedbackType: 0 })
  await motor.torControl({ torque: 1, feedbackType: 0 })
  assert.equal(adapter.fake.getRawSentMessages().length, 0)
  assert.ok(Number.isFinite(await motor.getParameter(api.MotorParameter.Position)))
  assert.equal(await motor.setCanTimeout(450), true)
  assert.equal(await motor.getParameter(api.MotorParameter.CanTimeout), 450)
  assert.equal((await motor.stop({ mode: api.MotorStopMode.FullBrake, current: 0, feedbackType: 1 })).noResponse, false)
  assert.equal(await motor.brake(true), true)
  assert.equal(bus.startImu(), true)
  assert.equal(bus.stopImu(), true)
  pms.sendCommand(api.PmsCommand.EnableChannel1)
  const motion = new Set([api.FakeCommandKind.PVTControl, api.FakeCommandKind.PosControl,
    api.FakeCommandKind.SpdControl, api.FakeCommandKind.CurControl, api.FakeCommandKind.TorControl])
  assert.equal(adapter.fake.getDecodedCommandRecords().filter(record => record.motorIndex === 1 && motion.has(record.kind)).length, 0)
  const raw = adapter.fake.getRawSentMessages()
  assert.ok(raw.some(message => message.data.id === 0x18f3fff2))
  assert.ok(raw.some(message => message.data.id === 0x0cf02d5a))
  bus.commit()
  assert.deepEqual(adapter.fake.getDecodedCommandRecords().filter(record => record.motorIndex === 1 && motion.has(record.kind)).map(record => record.kind), Array.from(motion))
})


test('64-byte raw messages pass native entry points and equality checks', async t => {
  const { runtime, adapter } = await fixture(t)
  const data = Array.from({ length: 64 }, (_, i) => i + 1)
  const message = { busIndex: 0, data: { id: 0x123, frameFlags: 6, len: 64, data } }
  adapter.fake.injectMessage(message)
  assert.equal(runtime.manager.dispatchUnknownReceive(adapter, 0, message.data), true)
  assert.equal(api.motorPackMessagesEqual(message.data, { ...message.data, data: [...data] }), true)
  const changed = [...data]
  changed[63] = 0
  assert.equal(api.motorPackMessagesEqual(message.data, { ...message.data, data: changed }), false)
  assert.throws(() => adapter.fake.injectMessage({ ...message, data: { ...message.data, len: 65, data: [...data, 1] } }))
  assert.throws(() => runtime.manager.dispatchUnknownReceive(adapter, 0, { ...message.data, len: 65, data: [...data, 1] }))
})
