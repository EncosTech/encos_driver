const root = process.env.ENCOS_NODE_PACKAGE_ROOT
if (!root) throw new Error('ENCOS_NODE_PACKAGE_ROOT is required')
const api = await import(pathToFileURL(resolve(root, 'dist/index-native.js')).href)
const model = api.MotorModel.EC_A4310_P2
async function fixture(t) {
  const runtime = await api.createEncosRuntime()
  t.after(() => runtime.dispose())
  const adapter = runtime.createFakeAdapter()
  adapter.fake.seedMotor(0, 1, model)
  return { runtime, adapter, bus: adapter.getBus(0) }
}

