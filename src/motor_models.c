/**
 * @brief 获取指定型号电机的控制量范围
 * @param[in] model 电机型号
 * @param[out] ranges 控制量范围输出
 * @return 成功返回 true，失败返回 false
 */
bool motor_get_model_ranges(MotorModel model, MotorRanges* ranges) {
    if (ranges == NULL) {
        return false;
    }
    for (size_t i = 0; i < sizeof(kMotorModels) / sizeof(kMotorModels[0]); ++i) {
        if (kMotorModels[i].model == model) {
            *ranges = kMotorModels[i].ranges;
            return true;
        }
    }
    return false;
}
