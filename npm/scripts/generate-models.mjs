import { readFileSync, writeFileSync } from 'node:fs'
const csv = new URL('../../src/device/motor/motor_models.csv', import.meta.url)
const names = readFileSync(csv, 'utf8').trim().split(/\r?\n/).slice(1).map(line => line.split(',')[0])
const text = '// SPDX-FileCopyrightText: 2026 Encos\n// SPDX-License-Identifier: MIT\n\n// Generated by npm/scripts/generate-models.mjs from motor_models.csv.\nexport const MotorModel = Object.freeze({\n' + names.map((name, index) => `  ${name}: ${index},`).join('\n') + '\n} as const)\n'
writeFileSync(new URL('../src/motor-models-generated.ts', import.meta.url), text)
